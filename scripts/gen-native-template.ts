/**
 * Writes lib/native/template-source.ts from template-native/, the files a phone or desktop product gets beyond the
 * template (docs/NATIVE.md). A deployed function has no template-native/ on disk to read, so provisionStep writes them into
 * the sandbox from this list, and they reach builds with no new snapshot. Run it after every edit to template-native/:
 *
 *   npx tsx scripts/gen-native-template.ts
 *
 * lib/native/__tests__/template-source.test.ts fails while the two differ.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.join(import.meta.dirname, "..");
const SOURCE = path.join(ROOT, "template-native");
const OUT = path.join(ROOT, "lib/native/template-source.ts");

const files = readdirSync(SOURCE, { recursive: true, withFileTypes: true })
  .filter((e) => e.isFile() && e.name !== ".DS_Store")
  .map((e) => path.relative(SOURCE, path.join(e.parentPath, e.name)).split(path.sep).join("/"))
  .sort();

const entries = files.map((file) => `  { path: ${JSON.stringify(file)}, content: ${JSON.stringify(readFileSync(path.join(SOURCE, file), "utf8"))} },`);
const module = [
  "// Generated by scripts/gen-native-template.ts from template-native/. Edit those files, not this one, then",
  "//   npx tsx scripts/gen-native-template.ts",
  "",
  "/** What a phone or desktop product gets beyond the template, by its path in the product (lib/native/template-files.ts). */",
  "export const NATIVE_TEMPLATE_FILES: ReadonlyArray<{ path: string; content: string }> = [",
  ...entries,
  "];",
  "",
].join("\n");
writeFileSync(OUT, module);
console.log(`Wrote ${path.relative(ROOT, OUT)} (${files.length} files).`);
