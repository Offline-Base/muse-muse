/**
 * Writes lib/sandbox/bridge-source.ts from lib/sandbox/bridge/bridge.mjs. A deployed function has no bridge.mjs on disk
 * to read, so builder.ts writes the bridge into each sandbox from this string. Run it after every edit to the bridge:
 *
 *   npx tsx scripts/gen-bridge-source.ts
 *
 * lib/sandbox/__tests__/bridge-source.test.ts fails while the two differ.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.join(import.meta.dirname, "..");
const SOURCE = path.join(ROOT, "lib/sandbox/bridge/bridge.mjs");
const OUT = path.join(ROOT, "lib/sandbox/bridge-source.ts");

const text = readFileSync(SOURCE, "utf8");
const module = [
  "// Generated by scripts/gen-bridge-source.ts from lib/sandbox/bridge/bridge.mjs. Edit the bridge, not this file, then",
  "//   npx tsx scripts/gen-bridge-source.ts",
  "",
  "/** The session bridge's source (lib/sandbox/bridge/bridge.mjs), which builder.ts writes into a sandbox before each start. */",
  `export const BRIDGE_SOURCE: string = ${JSON.stringify(text)};`,
  "",
].join("\n");
writeFileSync(OUT, module);
console.log(`Wrote ${path.relative(ROOT, OUT)} (${text.length} characters of bridge source).`);
