/**
 * Writes lib/outputs/assets-source.ts from lib/outputs/assets/. A deployed function has no such files on disk to read,
 * so the routes and the Prove it stage use these strings. Run it after every edit to an asset:
 *
 *   npx tsx scripts/gen-outputs-source.ts
 *
 * lib/outputs/__tests__/assets-source.test.ts fails while the two differ.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.join(import.meta.dirname, "..");
const DIR = path.join(ROOT, "lib/outputs/assets");
const OUT = path.join(ROOT, "lib/outputs/assets-source.ts");

const ASSETS: ReadonlyArray<{ name: string; file: string; about: string }> = [
  { name: "CLI_SOURCE", file: "cli.cjs", about: "The CLI, before a product's actions are written into it (generate.ts cliSource)." },
  { name: "PROVE_RUNNER_SOURCE", file: "prove-runner.mjs", about: "What runs each output against the live product, in the Prove it stage's sandbox." },
  { name: "PROVE_CHECK_PLUGIN_SOURCE", file: "prove-check-plugin.mjs", about: "The machine check of the Claude plugin's zip." },
  { name: "PROVE_SCENE_SOURCE", file: "prove-scene.html", about: "The terminal scene Demo Studio records." },
  { name: "GADGET_RUNNER_SOURCE", file: "gadget-runner.cjs", about: "The Muse gadget pack's runner, before a product's address and actions are written into it (gadget.ts)." },
  { name: "GADGET_INSTALL_SOURCE", file: "gadget-install.sh", about: "The Muse gadget pack's install.sh, before its names are written into it." },
  { name: "GADGET_UNINSTALL_SOURCE", file: "gadget-uninstall.sh", about: "The Muse gadget pack's uninstall.sh, before its names are written into it." },
  { name: "PROVE_CHECK_GADGET_SOURCE", file: "prove-check-gadget.mjs", about: "The machine check of the Muse gadget pack's zip." },
];

const module = [
  "// Generated by scripts/gen-outputs-source.ts from lib/outputs/assets/. Edit the assets, not this file, then",
  "//   npx tsx scripts/gen-outputs-source.ts",
  "",
  ...ASSETS.flatMap(({ name, file, about }) => [`/** ${about} */`, `export const ${name}: string = ${JSON.stringify(readFileSync(path.join(DIR, file), "utf8"))};`, ""]),
].join("\n");
writeFileSync(OUT, module);
console.log(`Wrote ${path.relative(ROOT, OUT)} from ${ASSETS.length} assets.`);
