/**
 * Writes lib/outputs/runtime-assets-source.ts from lib/outputs/runtime-assets/ (docs/CAPABILITIES.md, section 16). A
 * deployed function has no such files on disk to read, so the download routes use these strings. Run it after every
 * edit to an asset:
 *
 *   npx tsx scripts/gen-runtime-outputs-source.ts
 *
 * lib/outputs/__tests__/runtime-outputs.test.ts fails while the two differ.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.join(import.meta.dirname, "..");
const DIR = path.join(ROOT, "lib/outputs/runtime-assets");
const OUT = path.join(ROOT, "lib/outputs/runtime-assets-source.ts");

const RUNTIME_ASSETS: ReadonlyArray<{ name: string; file: string; about: string }> = [
  { name: "VSCODE_EXTENSION_SOURCE", file: "vscode-extension.cjs", about: "The VS Code extension's extension.js. It reads the product from product.json beside it." },
  { name: "GITHUB_ACTION_SOURCE", file: "github-action.cjs", about: "The GitHub Action's index.js. It reads the product from product.json beside it." },
  { name: "KIT_FETCH_SOURCE", file: "kit-fetch.mjs", about: "The self-host kit's scripts/kit-fetch.mjs, for the public files it leaves out." },
];

const module = [
  "// Generated by scripts/gen-runtime-outputs-source.ts from lib/outputs/runtime-assets/. Edit the assets, not this file, then",
  "//   npx tsx scripts/gen-runtime-outputs-source.ts",
  "",
  ...RUNTIME_ASSETS.flatMap(({ name, file, about }) => [`/** ${about} */`, `export const ${name}: string = ${JSON.stringify(readFileSync(path.join(DIR, file), "utf8"))};`, ""]),
].join("\n");
writeFileSync(OUT, module);
console.log(`Wrote ${path.relative(ROOT, OUT)} from ${RUNTIME_ASSETS.length} assets.`);
