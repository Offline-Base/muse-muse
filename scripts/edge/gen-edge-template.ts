/**
 * Writes lib/edge/template-source.ts from the template's edge files: the cloud-to-edge helper, its skill and the outage
 * drill kit. A deployed function can't read template/ from disk, so provisionStep writes these into the sandbox from
 * this list while EDGE_BUILDS is on, and they reach builds with no new builder snapshot. Run it after every edit to one
 * of them:
 *
 *   npx tsx scripts/edge/gen-edge-template.ts
 *
 * lib/edge/__tests__/template-source.test.ts fails while the two differ.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { EDGE_TEMPLATE_PATHS } from "@/lib/edge/paths";

const ROOT = path.join(import.meta.dirname, "../..");
const OUT = path.join(ROOT, "lib/edge/template-source.ts");

const entries = EDGE_TEMPLATE_PATHS.map((file) => `  { path: ${JSON.stringify(file)}, content: ${JSON.stringify(readFileSync(path.join(ROOT, "template", file), "utf8"))} },`);
const module = [
  "// Generated by scripts/edge/gen-edge-template.ts from the template files in lib/edge/paths.ts. Edit those files, not",
  "// this one, then run npx tsx scripts/edge/gen-edge-template.ts",
  "",
  "/** What a build gets while EDGE_BUILDS is on, by its path in the product (lib/edge/template-files.ts). */",
  "export const EDGE_TEMPLATE_FILES: ReadonlyArray<{ path: string; content: string }> = [",
  ...entries,
  "];",
  "",
].join("\n");
writeFileSync(OUT, module);
console.log(`Wrote ${path.relative(ROOT, OUT)} (${EDGE_TEMPLATE_PATHS.length} files).`);
