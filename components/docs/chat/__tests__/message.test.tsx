import assert from "node:assert/strict";
import { before, describe, it, mock } from "node:test";
import { createElement, type ComponentType } from "react";
import type { ChatPart } from "@/lib/docs/client/assistant";

// Server-renders the docs assistant's messages outside Next: Link is a stand-in.
mock.module("next/link", {
  defaultExport: (props: Record<string, unknown>) => createElement("a", { ...props, href: String(props.href) }),
});

let render: (c: ComponentType<never>, props: object) => string;
let Reply: ComponentType<never>;
let UserMessage: ComponentType<never>;

before(async () => {
  const { renderToString } = await import("react-dom/server");
  // React separates adjacent text with <!-- -->; drop it so assertions read like the page.
  render = (c, props) => renderToString(createElement(c, props as never)).replace(/<!-- -->/g, "");
  const message = await import("@/components/docs/chat/Message");
  Reply = message.Reply as ComponentType<never>;
  UserMessage = message.UserMessage as ComponentType<never>;
});

const searched: ChatPart = { kind: "tool", name: "search_docs", label: 'Searched the docs for "streaming"', state: "done" };
const running: ChatPart = { kind: "tool", name: "run_demo", label: "Running the demo", state: "running" };
const failed: ChatPart = { kind: "tool", name: "run_demo", label: "Ran the demo", state: "failed", detail: "Stopped." };
const picture: ChatPart = { kind: "images", srcs: ["data:image/png;base64,AAAA"] };
const answer: ChatPart = { kind: "text", text: "It's on [Streaming](/docs/streaming)." };

describe("docs assistant messages", () => {
  it("shows the reader's message as a bubble", () => {
    const html = render(UserMessage, { parts: [{ kind: "text", text: "Can you generate an image" }] });
    assert.equal(html, '<div class="chat-bubble"><p class="chat-bubble-text">Can you generate an image</p></div>');
  });

  it("shows each step as it runs, and Thinking... while it waits on the model", () => {
    const html = render(Reply, { parts: [searched, running], live: true });
    assert.match(html, /<div class="chat-step is-done">[\s\S]*?<title>Done<\/title>[\s\S]*?<p class="chat-step-title">Searched the docs for &quot;streaming&quot;<\/p><\/div>/);
    assert.match(html, /<div class="chat-step is-running"><span class="chat-step-icon"><svg class="chat-working-icon is-working"[\s\S]*?<p class="chat-step-title">Running the demo<\/p>/);
    assert.doesNotMatch(html, /Thinking\.\.\.|Show thinking/);
    const waiting = render(Reply, { parts: [searched], live: true });
    assert.match(waiting, /<div class="chat-step is-running">[\s\S]*?<p class="chat-step-title">Thinking\.\.\.<\/p><\/div>$/);
    assert.match(render(Reply, { parts: [], live: true }), /^<div class="chat-step is-running">[\s\S]*Thinking\.\.\./);
  });

  it("folds a finished reply's steps into Show thinking, then shows what the demo made and the answer", () => {
    const html = render(Reply, { parts: [searched, failed, picture, answer], live: false });
    assert.match(html, /^<button type="button" class="chat-thinking" aria-expanded="false" aria-controls="([^"]+)">[\s\S]*?Show thinking[\s\S]*?<\/button><div id="\1" class="docs-chat-steps" hidden=""><\/div>/);
    assert.doesNotMatch(html, /chat-step-title/, "the steps stay folded until asked for");
    assert.match(html, /<figure class="chat-media"><div class="chat-media-frame"><img src="data:image\/png;base64,AAAA" alt="Generated by the demo"\/><\/div><\/figure>/);
    assert.match(html, /<\/figure><div class="md">[\s\S]*<a href="\/docs\/streaming">Streaming<\/a>/, "docs links open in place");
  });

  it("has no Show thinking for a reply that took no steps", () => {
    assert.doesNotMatch(render(Reply, { parts: [answer], live: false }), /chat-thinking/);
  });

  it("keeps a reply that was stopped before its words unfolded, so the stopped step shows", () => {
    const html = render(Reply, { parts: [searched, failed], live: false });
    assert.doesNotMatch(html, /chat-thinking/);
    assert.match(html, /<div class="chat-step is-failed">[\s\S]*?<p class="chat-step-title">Ran the demo<\/p>[\s\S]*?<p class="chat-step-desc">Stopped\.<\/p>/);
  });
});
