"use client";

import { useId, useState } from "react";
import { MediaCard, ShowThinking, UserBubble, WorkingStep } from "@/components/chat";
import { replyView, userView, type ToolPart } from "@/components/docs/chat/reply";
import { MarkdownText } from "@/components/markdown/MarkdownText";
import type { ChatPart } from "@/lib/docs/client/assistant";

/** The reader's message, as the Muse app's bubble with any pictures in it as thumbnails. */
export function UserMessage({ parts }: { parts: readonly ChatPart[] }) {
  const { text, images } = userView(parts);
  return <UserBubble text={text} attachments={images.map((src, i) => ({ src, alt: `Picture ${i + 1} you sent` }))} />;
}

/**
 * The assistant's reply. While it runs, each step shows as a working step and its words stream in below, with
 * "Thinking..." whenever it waits on the model. Once done, its steps fold into "Show thinking", which unfolds them
 * right here (the sidebar has no room for a second panel), and the demo's pictures and the answer stay below.
 */
export function Reply({ parts, live }: { parts: readonly ChatPart[]; live: boolean }) {
  const view = replyView(parts, live);
  return (
    <>
      {view.folded.length ? <FoldedSteps steps={view.folded} /> : null}
      {view.shown.map((p, j) => (
        <Part key={j} part={p} streaming={live && j === parts.length - 1} />
      ))}
      {view.waiting ? <WorkingStep title="Thinking..." state="running" /> : null}
    </>
  );
}

function FoldedSteps({ steps }: { steps: readonly ToolPart[] }) {
  const [open, setOpen] = useState(false);
  const id = useId();
  return (
    <>
      <ShowThinking expanded={open} controls={id} onClick={() => setOpen((v) => !v)} />
      <div id={id} className="docs-chat-steps" hidden={!open}>
        {open ? steps.map((p, j) => <Step key={j} part={p} />) : null}
      </div>
    </>
  );
}

function Step({ part }: { part: ToolPart }) {
  return <WorkingStep title={part.label} description={part.detail} state={part.state} />;
}

function Part({ part, streaming }: { part: ChatPart; streaming: boolean }) {
  if (part.kind === "tool") return <Step part={part} />;
  if (part.kind === "images") {
    return part.srcs.map((src) => (
      <MediaCard key={src}>
        {/* Generated by a demo on this page (isChatImageSrc): next/image can't optimize a data URL. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src={src} alt="Generated by the demo" />
      </MediaCard>
    ));
  }
  return <MarkdownText text={part.text} streaming={streaming} docsLinks />;
}
